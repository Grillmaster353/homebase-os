_PREFIXES = {prefix: (brand, manufacturer) for brand, manufacturer, prefixes in _REGISTRANTS for prefix in prefixes.split()}
PREFIX_COUNT = len(_PREFIXES)

def normalize_mac(value) -> str | None:
    if not isinstance(value, str) or len(value) > 32:
        return None
    value = value.strip()
    if re.fullmatch(r"[0-9a-fA-F]{12}", value):
        raw = value
    elif re.fullmatch(r"[0-9a-fA-F]{4}(?:\.[0-9a-fA-F]{4}){2}", value):
        raw = value.replace(".", "")
    elif re.fullmatch(r"[0-9a-fA-F]{1,2}(?::[0-9a-fA-F]{1,2}){5}", value):
        raw = "".join(part.zfill(2) for part in value.split(":"))
    elif re.fullmatch(r"[0-9a-fA-F]{2}(?:-[0-9a-fA-F]{2}){5}", value):
        raw = value.replace("-", "")
    else:
        return None
    # The I/G and U/L bits distinguish group/local from globally assigned MACs.
    if int(raw[:2], 16) & 3 or int(raw, 16) == 0:
        return None
    return raw.upper()


def lookup_router_brand(mac) -> dict | None:
    normalized = normalize_mac(mac)
    if not normalized:
        return None
    entry = _PREFIXES.get(normalized[:6])
    if not entry:
        return None
    identity, manufacturer = entry
    return {"id": identity, "name": BRANDS[identity], "manufacturer": manufacturer,
            "source": SOURCE, "prefix": normalized[:6], "sourceUrl": SOURCE_URL,
            "snapshotDate": SNAPSHOT_DATE}
